/* Generates the extra LMS/XMSS verify vectors in certs/out/ese_hbs_data.c. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <wolfssl/wolfcrypt/settings.h>
#include <wolfssl/wolfcrypt/random.h>
#include <wolfssl/wolfcrypt/wc_lms.h>
#include <wolfssl/wolfcrypt/wc_xmss.h>
#include <wolfssl/wolfcrypt/error-crypt.h>

#include "ese_algs.h"

#ifdef ESE_ALL_PQC_PARAMS

#define CHECK(x) do { int r_ = (x); if (r_ < 0) { \
    fprintf(stderr, "%s:%d %s = %d\n", __FILE__, __LINE__, #x, r_); \
    exit(1); } } while (0)

static const struct {
    const char *name;
    enum wc_LmsParm lms_parm;
    const char *xmss_parm;
} sets[] = {
    { "lms_h10_w1",    WC_LMS_PARM_L1_H10_W1, NULL },
    { "lms_h10_w2",    WC_LMS_PARM_L1_H10_W2, NULL },
    { "lms_h10_w8",    WC_LMS_PARM_L1_H10_W8, NULL },
    { "lms_h20_w4",    WC_LMS_PARM_L1_H20_W4, NULL },
    { "lms_l2_h10_w4", WC_LMS_PARM_L2_H10_W4, NULL },
    { "lms192_h10_w4", WC_LMS_PARM_SHA256_192_L1_H10_W4, NULL },
    { "xmss_h20",      WC_LMS_PARM_NONE, "XMSS-SHA2_20_256" },
    { "xmssmt_h20_d2", WC_LMS_PARM_NONE, "XMSSMT-SHA2_20/2_256" },
    { "xmssmt_h40_d4", WC_LMS_PARM_NONE, "XMSSMT-SHA2_40/4_256" },
};

static byte *priv_buf;
static word32 priv_len;

static int save(const byte *p, word32 sz)
{
    if (sz > priv_len) {
        priv_buf = realloc(priv_buf, sz);
        if (priv_buf == NULL) {
            return 0;
        }
    }
    memcpy(priv_buf, p, sz);
    priv_len = sz;
    return 1;
}

static int load(byte *p, word32 sz)
{
    if (priv_buf == NULL || sz != priv_len) {
        return 0;
    }
    memcpy(p, priv_buf, sz);
    return 1;
}

static int lms_write(const byte *p, word32 sz, void *ctx)
{
    (void)ctx;
    return save(p, sz) ? WC_LMS_RC_SAVED_TO_NV_MEMORY : WC_LMS_RC_WRITE_FAIL;
}

static int lms_read(byte *p, word32 sz, void *ctx)
{
    (void)ctx;
    return load(p, sz) ? WC_LMS_RC_READ_TO_MEMORY : WC_LMS_RC_READ_FAIL;
}

static enum wc_XmssRc xmss_write(const byte *p, word32 sz, void *ctx)
{
    (void)ctx;
    return save(p, sz) ? WC_XMSS_RC_SAVED_TO_NV_MEMORY : WC_XMSS_RC_WRITE_FAIL;
}

static enum wc_XmssRc xmss_read(byte *p, word32 sz, void *ctx)
{
    (void)ctx;
    return load(p, sz) ? WC_XMSS_RC_READ_TO_MEMORY : WC_XMSS_RC_READ_FAIL;
}

static void emit(FILE *f, const char *sym, const byte *b, word32 sz)
{
    word32 i;

    fprintf(f, "static const unsigned char %s[%u] = {", sym, sz);
    for (i = 0; i < sz; i++) {
        fprintf(f, "%s0x%02x,", (i % 16) == 0 ? "\n    " : " ", b[i]);
    }
    fprintf(f, "\n};\n\n");
}

int main(int argc, char **argv)
{
    byte msg[ESE_BENCH_MSG_LEN];
    byte pub[128];
    word32 pub_sz, sig_sz;
    byte *sig;
    WC_RNG rng;
    FILE *f;
    char sym[64];
    size_t i;
    size_t n = sizeof(sets) / sizeof(sets[0]);

    if (argc != 2 || (f = fopen(argv[1], "w")) == NULL) {
        fprintf(stderr, "usage: %s <out .c>\n", argv[0]);
        return 1;
    }
    CHECK(wc_InitRng(&rng));
    ese_bench_msg(msg);
    fprintf(f, "/* Generated by certs/gen/hbsgen.c; do not edit. */\n"
               "#include <stddef.h>\n\n#include \"ese_certs.h\"\n\n#ifdef ESE_ALL_PQC_PARAMS\n\n");

    for (i = 0; i < n; i++) {
        printf("%s\n", sets[i].name);
        fflush(stdout);
        pub_sz = sizeof(pub);
        if (sets[i].xmss_parm == NULL) {
            LmsKey *k = calloc(1, sizeof(*k));
            CHECK(wc_LmsKey_Init(k, NULL, INVALID_DEVID));
            CHECK(wc_LmsKey_SetLmsParm(k, sets[i].lms_parm));
            CHECK(wc_LmsKey_SetWriteCb(k, lms_write));
            CHECK(wc_LmsKey_SetReadCb(k, lms_read));
            CHECK(wc_LmsKey_SetContext(k, NULL));
            CHECK(wc_LmsKey_MakeKey(k, &rng));
            CHECK(wc_LmsKey_GetSigLen(k, &sig_sz));
            sig = malloc(sig_sz);
            CHECK(wc_LmsKey_Sign(k, sig, &sig_sz, msg, (int)sizeof(msg)));
            CHECK(wc_LmsKey_ExportPubRaw(k, pub, &pub_sz));
            wc_LmsKey_Free(k);
            free(k);
        }
        else {
            XmssKey *k = calloc(1, sizeof(*k));
            CHECK(wc_XmssKey_Init(k, NULL, INVALID_DEVID));
            CHECK(wc_XmssKey_SetParamStr(k, sets[i].xmss_parm));
            CHECK(wc_XmssKey_SetWriteCb(k, xmss_write));
            CHECK(wc_XmssKey_SetReadCb(k, xmss_read));
            CHECK(wc_XmssKey_SetContext(k, NULL));
            CHECK(wc_XmssKey_MakeKey(k, &rng));
            CHECK(wc_XmssKey_GetSigLen(k, &sig_sz));
            sig = malloc(sig_sz);
            CHECK(wc_XmssKey_Sign(k, sig, &sig_sz, msg, (int)sizeof(msg)));
            CHECK(wc_XmssKey_ExportPubRaw(k, pub, &pub_sz));
            wc_XmssKey_Free(k);
            free(k);
        }
        snprintf(sym, sizeof(sym), "%s_pub", sets[i].name);
        emit(f, sym, pub, pub_sz);
        snprintf(sym, sizeof(sym), "%s_sig", sets[i].name);
        emit(f, sym, sig, sig_sz);
        free(sig);
    }

    fprintf(f, "const ese_hbs_vec_t ese_hbs_vecs[] = {\n");
    for (i = 0; i < n; i++) {
        const char *x = sets[i].xmss_parm;
        fprintf(f, "    { \"%s\", %d, %s%s%s, %s_pub, sizeof(%s_pub),\n"
                   "      %s_sig, sizeof(%s_sig) },\n",
                sets[i].name, (int)sets[i].lms_parm, x ? "\"" : "",
                x ? x : "NULL", x ? "\"" : "", sets[i].name, sets[i].name,
                sets[i].name, sets[i].name);
    }
    fprintf(f, "};\nconst int ese_hbs_vec_count = %d;\n\n"
               "#endif /* ESE_ALL_PQC_PARAMS */\n", (int)n);
    fclose(f);
    wc_FreeRng(&rng);
    return 0;
}

#else

int main(void)
{
    fprintf(stderr, "ese_hbsgen needs a build with ESE_ALL_PQC_PARAMS\n");
    return 1;
}

#endif /* ESE_ALL_PQC_PARAMS */
